def fixed(width):
    """Right-aligned column of fixed width, so a wide group heading spreads evenly over its columns."""
    return r">{\raggedleft\arraybackslash}p{" + width + "}"
SPECS = [("all18", "none"), ("all18", "single_turn"), ("known_params12", "none"), ("known_params12", "single_turn"), ("known_params12", "log_params"), ("known_params12", "single_turn_and_log_params")]


def read(name):
    with (SOURCE / name).open() as handle:
        return list(csv.DictReader(handle))


def esc(text):
    return str(text).replace("_", r"\_").replace("%", r"\%").replace("&", r"\&")


def line(*values):
    return " & ".join(map(str, values)) + r" \\" + "\n"


def estimate(row, key="tau_b", undefined=False, bold=False):
    interval = f"[{float(row['ci95_low']):.3f}, {float(row['ci95_high']):.3f}]"
    point = f"{float(row[key]):.3f}"
    if bold:
        point = r"\textbf{" + point + "}"
    cell = r"\shortstack[r]{" + point + r"\\[-1pt]{\scriptsize " + interval + "}"
    if undefined:
        cell += r"\\[-1pt]{\scriptsize $u=" + row["boot_undefined"] + "$}"
    return cell + "}"


def save(name, text):
    (OUT / name).write_text("% Generated by gen_tables.py from verified panel18 artifacts.\n" + text)


def table(name, label, caption, headers, rows, spec=None, wide=True, colsep=4, floating=True, placement="t"):
    env = "table*" if wide else "table"
    spec = spec or ("l" + "r" * (len(headers) - 1))
    if floating:
        text = f"\\begin{{{env}}}[{placement}]\n"
    else:
        width = r"\textwidth" if wide else r"\columnwidth"
        text = f"\\begin{{minipage}}[t]{{{width}}}\n\\vspace{{0pt}}\n"
    text += f"\\centering\n\\small\n\\setlength{{\\tabcolsep}}{{{colsep}pt}}\n"
    text += f"\\begin{{tabular}}{{{spec}}}\n\\toprule\n"
    text += line(*headers) + "\\midrule\n" + "".join(line(*r) for r in rows)
    text += "\\bottomrule\n\\end{tabular}\n"
    text += f"\\caption{{{caption}}}\n\\label{{{label}}}\n"
    text += f"\\end{{{env}}}\n" if floating else "\\end{minipage}\n"
    save(name, text)


def appendix_table(name, label, caption, headers, rows, spec=None, header=None, wide=True, colsep=3, floating=True):
    """Typeset one- or two-column floats, splitting long tables into parts.

    `header` optionally replaces the single header row with pre-rendered rows (grouped column names)."""
    spec = spec or ("l" + "r" * (len(headers) - 1))
    env = "table*" if wide else "table"
    chunk_size = 18 if len(rows) % 18 == 0 else 24
    chunks = [rows[start:start + chunk_size] for start in range(0, len(rows), chunk_size)]
    text = ""
    for part, chunk in enumerate(chunks, 1):
        part_label = label if part == 1 else f"{label}:continued-{part}"
        part_caption = caption
        if len(chunks) > 1:
            part_caption += f" Part {part} of {len(chunks)}."
            if part > 1:
                part_caption += f" Continued from Table~\\ref{{{label}}}."
        if floating:
            text += f"\\begin{{{env}}}[t]\n"
        else:
            width = r"\textwidth" if wide else r"\columnwidth"
            text += f"\\begin{{minipage}}[t]{{{width}}}\n"
        text += f"\\centering\n\\footnotesize\n\\setlength{{\\tabcolsep}}{{{colsep}pt}}\n"
        text += f"\\begin{{tabular}}{{{spec}}}\n\\toprule\n"
        text += (header or line(*headers)) + "\\midrule\n"
        text += "".join(line(*r) for r in chunk)
        text += "\\bottomrule\n\\end{tabular}\n"
        text += f"\\caption{{{part_caption}}}\n\\label{{{part_label}}}\n"
        text += f"\\end{{{env}}}\n" if floating else "\\end{minipage}\n"
    assert sum(map(len, chunks)) == len(rows)
    save(name, text)


