#!/usr/bin/env python3
"""Typeset the BFCL-high subset from existing results; no statistics."""
from __future__ import annotations

import json
from pathlib import Path

from gen_tables import ABBREV, CLABEL, CRITERIA, DIFF, NAME, esc, estimate, line

HERE = Path(__file__).resolve().parent
SOURCE = HERE.parent / "results/bfcl_high_subset_20261004"
OUT = HERE / "tables"


def table(name, label, caption, headers, rows, header=None):
    """Use the main generator's full-width table and numeric-cell style.

    `header` optionally replaces the single header row with pre-rendered rows (grouped column names)."""
    spec = "l" + "r" * (len(headers) - 1)
    text = "% Generated by gen_high_subset_tables.py from verified subset artifacts.\n"
    text += "\\begin{table*}[t]\n\\centering\n\\small\n\\setlength{\\tabcolsep}{4pt}\n"
    text += f"\\begin{{tabular}}{{{spec}}}\n\\toprule\n"
    text += (header or line(*headers)) + "\\midrule\n" + "".join(line(*r) for r in rows)
    text += "\\bottomrule\n\\end{tabular}\n"
    text += f"\\caption{{{caption}}}\n\\label{{{label}}}\n\\end{{table*}}\n"
    (OUT / name).write_text(text)


def subset_estimate(row, key):
    if row[key] is None:
        assert row["ci95_low"] is None and row["ci95_high"] is None
        return "Undefined"
    return estimate(row, key)


def main():
    report = json.loads((SOURCE / "analysis.json").read_text())
    members = report["members"]
    associations = report["associations"]
    differences = report["paired_differences"]
    assert len(members) == 6 and len(associations) == 9 and len(differences) == 6
    assert all(r["bfcl_overall"] >= 50 for r in members)
    assert all(r["C_correct"] == r["C_n"] == 90 for r in members)
    assert report["meta"]["bootstrap"]["n"] == 10000
    assert report["meta"]["bootstrap"]["seed"] == 42
    index = {(r["block"], r["criterion"]): r for r in associations}
    difference_index = {(r["comparison"], r["criterion"]): r for r in differences}
    rows = []
    for probe, key, source in [
        ("A", "tau_b", index),
        ("C", "tau_b", index),
        ("D", "tau_b", index),
        ("A-C", "delta_tau_b", difference_index),
        ("A-D", "delta_tau_b", difference_index),
    ]:
        records = [source[probe, criterion] for criterion in CRITERIA]
        counts = {(r["boot_valid"], r["boot_undefined"]) for r in records}
        assert len(counts) == 1
        valid, undefined = counts.pop()
        assert valid + undefined == 10000
        label = NAME[probe] if key == "tau_b" else DIFF[probe]
        rows.append([label] + [subset_estimate(r, key) for r in records] + [valid, undefined])
    OUT.mkdir(exist_ok=True)
    table(
        "high_subset_associations.tex",
        "tab:high-subset-associations",
        r"All nine associations and six paired differences for the BFCL Overall $\geq 50$ subgroup ($n=6$). "
        r"Cells show Kendall $\tau_b$ for the core, arithmetic, and cancellation items, or paired differences in "
        r"$\tau_b$ (Core $-$ Arith. and Core $-$ Cancel.), with pointwise 95\% percentile intervals "
        r"from 10,000 paired model-bootstrap resamples (seed 42). Intervals use only defined resamples, without "
        r"multiplicity adjustment or task resampling. Valid and $u$ are defined and undefined resample counts, "
        r"identical across the three criteria within each row. The arithmetic score is constant at 90/90 for all "
        r"six models, so the Arithmetic and Core $-$ Arith. rows are undefined rather than zero. " + ABBREV,
        ["Probe / contrast"] + [CLABEL[c] for c in CRITERIA] + ["Valid", "$u$"],
        rows,
    )
    rows = [
        [esc(r["model"])]
        + [r[k] for k in ("A_correct", "A_one_integer", "A_truncated", "D_correct")]
        + [f"{r['bfcl_' + c]:.2f}" for c in CRITERIA]
        for r in members
    ]
    headers = ["Model", r"\shortstack{Corr\\/60}", r"\shortstack{1 int\\/60}",
               r"\shortstack{Trunc\\/60}", r"\shortstack{Corr\\/100}", "Overall", "MT", "Agentic"]
    header = (r" & \multicolumn{3}{c}{" + NAME["A"] + "} & " + NAME["D"] + r" & \multicolumn{3}{c}{BFCL} \\" + "\n"
              + r"\cmidrule(lr){2-4}\cmidrule(lr){5-5}\cmidrule(lr){6-8}" + "\n" + line(*headers))
    table(
        "high_subset_scores.tex",
        "tab:high-subset-scores",
        r"All six models with BFCL Overall $\geq 50$ in the 2025-12-16 FC snapshot. "
        r"Core columns are correct (Corr), exactly one integer (1 int), and truncated (Trunc), each out of 60. "
        r"1 int is a correctness requirement, and truncation is an overlapping marker. Cancellation shows correct "
        r"counts out of 100. All six models score 90/90 on the arithmetic items. The final three columns are BFCL "
        r"percentages (MT is Multi-Turn).",
        headers,
        rows,
        header=header,
    )
    print("Generated two BFCL-high-subset tables without recomputing statistics.")


if __name__ == "__main__":
    main()
