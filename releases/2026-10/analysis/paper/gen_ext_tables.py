#!/usr/bin/env python3
"""Typeset blocks K and L from the existing analysis outputs; no statistics.

Reads analysis/results/ext/ (analysis.json, accuracy_by_model.csv) and the
panel list, writes tables/ext_by_model.tex and tables/ext_summary.tex.
A panel model without results is listed as not run.
"""
from __future__ import annotations

import csv
import json
import sys
from pathlib import Path

from gen_tables import fixed, line

HERE = Path(__file__).resolve().parent
PANEL = HERE.parent / "results/BFCL_INPUTS_20261004.csv"
OUT = HERE / "tables"
CELLS = ["K_q1", "K_q2", "K_q3", "L_M1_tracking", "L_M2_tracking", "L_M4_tracking",
         "L_M1_readout", "L_M2_readout", "L_M4_readout"]


def save(name: str, text: str) -> None:
    (OUT / name).write_text("% Generated by gen_ext_tables.py from the saved analysis of the intermediate-state and multi-target items (codes K and L).\n" + text)


def pct(value: float) -> str:
    return f"{100 * value:.1f}".replace("-", "$-$")


def interval(cell: dict) -> str:
    return f"[{pct(cell['ci95'][0])}, {pct(cell['ci95'][1])}]"


def float_table(spec: str, header: str, body: str, caption: str, label: str) -> str:
    return ("\\begin{table*}[t]\n\\centering\n\\footnotesize\n\\setlength{\\tabcolsep}{3pt}\n"
            f"\\begin{{tabular}}{{{spec}}}\n\\toprule\n{header}\\midrule\n{body}\\bottomrule\n\\end{{tabular}}\n"
            f"\\caption{{{caption}}}\n\\label{{{label}}}\n\\end{{table*}}\n")


def main() -> None:
    source = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE.parent / "results/ext"
    analysis = json.loads((source / "analysis.json").read_text())
    by_model = {row["model"]: row for row in csv.DictReader((source / "accuracy_by_model.csv").open())}
    panel = list(csv.DictReader(PANEL.open()))
    labels = {r["run_label"]: r["model"].replace("-Instruct", "").replace("-350m", "-350M") for r in panel}
    assert set(by_model) <= set(labels) and len(by_model) == analysis["meta"]["n_models"]
    not_run = [labels[r["run_label"]] for r in panel if r["run_label"] not in by_model]

    rows, totals = "", [0] * len(CELLS)
    for r in panel:
        label = r["run_label"]
        if label not in by_model:
            rows += line(labels[label], *["--"] * (len(CELLS) + 2))
            continue
        row = by_model[label]
        counts = [int(row[c].split("/")[0]) for c in CELLS]
        assert all(row[c].endswith("/20") for c in CELLS) and row["answered"] == "180"
        totals = [a + b for a, b in zip(totals, counts)]
        rows += line(labels[label], *counts, int(row["K_compliant"]) + int(row["L_compliant"]),
                     int(row["K_truncated"]) + int(row["L_truncated"]))
    n = len(by_model)
    pooled = [analysis["K"]["accuracy_by_query_position"][f"q{q}"]["correct"] for q in (1, 2, 3)]
    pooled += [analysis["L"]["accuracy"][f"M{m}_{c}"]["correct"] for c in ("tracking", "readout") for m in (1, 2, 4)]
    assert pooled == totals
    rows += "\\midrule\n" + line(r"\rowcolor{black!9} \textbf{" + f"All {n} models (of {20 * n})" + "}",
                                     *[r"\textbf{" + str(value) + "}" for value in totals], "", "")
    header = (" & \\multicolumn{3}{c}{Intermediate states} & \\multicolumn{3}{c}{Multi-target tracking} & "
              "\\multicolumn{3}{c}{Multi-target readout} & & \\\\\n"
              " & \\multicolumn{3}{c}{after update} & \\multicolumn{3}{c}{$M$} & \\multicolumn{3}{c}{$M$} & & \\\\\n"
              "\\cmidrule(lr){2-4}\\cmidrule(lr){5-7}\\cmidrule(lr){8-10}\n"
              + line("Model", 1, 2, 3, 1, 2, 4, 1, 2, 4, "Format", "Truncated"))
    caption = ("Correct responses out of 20 per cell for the intermediate-state queries and the multi-target items. "
               "Intermediate-state columns give the queried update. Multi-target columns give the number of queried "
               "entities $M$ for tracking and for the matched readout control. Format counts responses with exactly the requested number of integers and "
               "Truncated counts responses that reached the output limit, both out of 180.")
    if not_run:
        caption += " " + ", ".join(not_run) + (" was" if len(not_run) == 1 else " were") + " not run on these blocks."
    save("ext_by_model.tex", float_table("l" + fixed("22pt") * 9 + "rr", header, rows, caption, "tab:ext-by-model"))

    k, l = analysis["K"], analysis["L"]
    body = ""
    for q in (1, 2, 3):
        cell = k["accuracy_by_query_position"][f"q{q}"]
        body += line(f"State {q}", f"{cell['correct']}/{cell['answered']}", pct(cell["mean_over_models"]), interval(cell))
    for cond, name in (("tracking", "Tracking"), ("readout", "Readout")):
        body += "\\addlinespace[2pt]\n"
        for m in (1, 2, 4):
            cell = l["accuracy"][f"M{m}_{cond}"]
            body += line(f"{name}, $M={m}$", f"{cell['correct']}/{cell['answered']}", pct(cell["mean_over_models"]), interval(cell))
    right_body = ""
    diffs = [("State $2-1$", k["paired_differences"]["q2_minus_q1"]),
             ("State $3-2$", k["paired_differences"]["q3_minus_q2"]),
             ("State $3-1$", k["paired_differences"]["q3_minus_q1"]),
             ("Slot-position", k["by_position_guess"]["agrees_minus_disagrees"])]
    diffs += [(f"R$-$T, $M={m}$", l["readout_minus_tracking"][f"M{m}"]) for m in (1, 2, 4)]
    diffs += [("T, $M=4$ minus $1$", l["tracking_M4_minus_M1"]),
              ("R, $M=4$ minus $1$", l["readout_M4_minus_M1"])]
    for i, (name, cell) in enumerate(diffs):
        if i in (4, 7):
            right_body += "\\addlinespace[2pt]\n"
        right_body += line(name, pct(cell["mean_over_models"]), interval(cell))
    caption = f"Intermediate-state and multi-target results ({n} models). Pooled correct counts and mean model accuracy (left), paired differences in percentage points (right). States 1--3 index the queried entity's updates. $M$ counts queried entities, and T/R denote tracking/readout. Positive differences favor the first term. Slot-position compares queries where $\\lceil s/3\\rceil$ correctly counts target updates with the rest (first minus second), where $s$ is the queried slot. Intervals are pointwise 95\\% percentile model-bootstrap intervals (10,000 resamples)."
    def panel(spec: str, header: str, content: str) -> str:
        return ("\\begin{minipage}[t]{0.49\\textwidth}\n\\vspace{0pt}\n\\centering\n"
                f"\\begin{{tabular}}{{{spec}}}\n\\toprule\n{header}\\midrule\n{content}\\bottomrule\n\\end{{tabular}}\n\\end{{minipage}}")
    text = ("\\begin{table*}[t]\n\\centering\n\\footnotesize\n\\setlength{\\tabcolsep}{3pt}\n"
            + panel("@{}lrrr@{}", line("Condition", r"Correct $\uparrow$", r"Accuracy (\%) $\uparrow$", "95\\% interval"), body) + "\\hfill\n"
            + panel("@{}lrr@{}", line("Contrast", "Difference (pp)", "95\\% interval"), right_body) + "\n"
            + f"\\caption{{{caption}}}\n\\label{{tab:ext-summary}}\n\\end{{table*}}\n")
    save("ext_summary.tex", text)
    print(f"wrote ext_by_model.tex and ext_summary.tex for {n} models; not run: {not_run}")


if __name__ == "__main__":
    main()
